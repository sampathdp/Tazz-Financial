/* Tazz Investment & Credit — Document Tracking (read-only log of every generated reference number) */
import { useEffect, useRef, useState } from 'react'
import { Card, PageHead, Badge, Input, Select, Table, Td, Pager, LoadingBlock } from '../components/ui'
import { Icon } from '../components/Icon'
import { generatedNumbersApi, type GeneratedNumber } from '../api'
import type { ScreenProps } from './types'

const MODULE_LABELS: Record<string, string> = {
  loan: 'Loan', customer: 'Customer', payment: 'Payment',
  speed_draft: 'Speed Draft', speed_draft_payment: 'Speed Draft Payment',
  fd_deposit: 'FD Deposit', fixed_deposit: 'Fixed Deposit', fd_withdrawal: 'FD Withdrawal',
  journal: 'Journal Entry', expense: 'Expense', payment_voucher: 'Payment Voucher',
  petty_cash_fund: 'Petty Cash Fund', petty_cash_replenishment: 'Petty Cash Top-up', petty_cash_voucher: 'Petty Cash Voucher',
}
const moduleTone: Record<string, 'blue' | 'green' | 'amber' | 'neutral'> = {
  loan: 'blue', customer: 'green', payment: 'amber',
  speed_draft: 'blue', speed_draft_payment: 'amber',
  fd_deposit: 'green', fixed_deposit: 'blue', fd_withdrawal: 'amber',
  journal: 'neutral', expense: 'amber', payment_voucher: 'amber',
  petty_cash_fund: 'green', petty_cash_replenishment: 'blue', petty_cash_voucher: 'amber',
}
// The full, fixed universe of modules — not derived from whatever page of
// rows happens to be loaded (see the old client-side-filter bug this
// replaced: a module/year with no rows in the most recent 500 wouldn't even
// appear as a selectable filter option).
const MODULES = Object.keys(MODULE_LABELS)

export function DocumentTrackingScreen(_props: ScreenProps) {
  const [rows, setRows] = useState<GeneratedNumber[]>([])
  const [page, setPage] = useState(1)
  const [lastPage, setLastPage] = useState(1)
  const [total, setTotal] = useState(0)
  const [years, setYears] = useState<number[]>([])
  const [loading, setLoading] = useState(true)
  const [search, setSearch] = useState('')
  const [debouncedSearch, setDebouncedSearch] = useState('')
  const [module, setModule] = useState('')
  const [year, setYear] = useState('')

  useEffect(() => {
    generatedNumbersApi.years().then(setYears).catch(() => setYears([]))
  }, [])

  // Search text is debounced so a keystroke doesn't fire a request per
  // character; module/year/page changes refresh immediately.
  const debounceRef = useRef<ReturnType<typeof setTimeout>>()
  useEffect(() => {
    if (debounceRef.current) clearTimeout(debounceRef.current)
    debounceRef.current = setTimeout(() => setDebouncedSearch(search.trim()), 300)
    return () => { if (debounceRef.current) clearTimeout(debounceRef.current) }
  }, [search])

  // A filter change always jumps back to page 1.
  useEffect(() => { setPage(1) }, [module, year, debouncedSearch])

  useEffect(() => {
    setLoading(true)
    generatedNumbersApi.browse({ search: debouncedSearch || undefined, module: module || undefined, year: year || undefined, page })
      .then((r) => { setRows(r.data); setLastPage(r.lastPage); setTotal(r.total) })
      .catch(() => { setRows([]); setLastPage(1); setTotal(0) })
      .finally(() => setLoading(false))
  }, [module, year, debouncedSearch, page])

  return (
    <div>
      <PageHead crumbs="Loan Management" title="Document Tracking" icon="doc"
        sub="Every reference number ever issued — loans, customers, payments — for audit and traceability." />
      <Card pad={0}>
        <div className="row gap-2" style={{ padding: '12px 16px', borderBottom: '1px solid var(--line)', alignItems: 'center' }}>
          <div style={{ position: 'relative', maxWidth: 260, flex: 1 }}>
            <span style={{ position: 'absolute', left: 10, top: '50%', transform: 'translateY(-50%)', color: 'var(--tx-2)' }}><Icon n="search" s={15} /></span>
            <Input value={search} onChange={(e) => setSearch(e.target.value)} placeholder="Search number…" style={{ paddingLeft: 32 }} />
          </div>
          <Select value={module} onChange={(e) => setModule(e.target.value)} style={{ maxWidth: 160 }}>
            <option value="">All modules</option>
            {MODULES.map((m) => <option key={m} value={m}>{MODULE_LABELS[m] || m}</option>)}
          </Select>
          <Select value={year} onChange={(e) => setYear(e.target.value)} style={{ maxWidth: 120 }}>
            <option value="">All years</option>
            {years.map((y) => <option key={y} value={y}>{y}</option>)}
          </Select>
          <span className="t-2" style={{ fontSize: 12 }}>{total} match{total === 1 ? '' : 'es'}</span>
        </div>
        {loading ? <LoadingBlock /> : <>
        <Table cols={[
          { label: 'Number' }, { label: 'Module' }, { label: 'Branch' }, { label: 'Loan Type' },
          { label: 'Year', align: 'center' }, { label: 'Seq', align: 'center' }, { label: 'Generated By' }, { label: 'Date' },
        ]}
          rows={rows}
          empty={search.trim() || module || year ? 'No numbers match your filters' : 'Nothing generated yet'}
          render={(g) => <>
            <Td mono style={{ fontWeight: 600 }}>{g.number}</Td>
            <Td><Badge tone={moduleTone[g.module] || 'neutral'}>{MODULE_LABELS[g.module] || g.module}</Badge></Td>
            <Td>{g.branch?.name || '—'}</Td>
            <Td>{g.loanType?.name || '—'}</Td>
            <Td align="center">{g.year || '—'}</Td>
            <Td align="center" mono>{g.sequence}</Td>
            <Td>{g.generator?.name || '—'}</Td>
            <Td style={{ fontSize: 12 }}>{g.createdAt ? new Date(g.createdAt).toLocaleString() : '—'}</Td>
          </>} />
        <Pager page={page} lastPage={lastPage} total={total} onChange={setPage} />
        </>}
      </Card>
    </div>
  )
}
